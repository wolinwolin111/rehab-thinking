import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { isReleaseFingerprintExcluded, RELEASE_FINGERPRINT_EXCLUDED_PATHS } from "../quality/release-fingerprint-core.mjs";

const root = path.resolve(import.meta.dirname, "../..");
const packageMetadata = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const generatedReleasePath = "src/infrastructure/pilot/release/release.generated.ts";

function git(args, fallback) {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || fallback;
  } catch {
    return fallback;
  }
}

function releaseValue(value, fallback) {
  const normalized = String(value ?? fallback).trim().replace(/[^A-Za-z0-9._+-]/g, "-");
  if (!normalized) throw new Error("pilot release values must not be empty");
  return normalized;
}

function worktreeFingerprint() {
  const hash = createHash("sha256");
  const trackedDiff = git([
    "diff",
    "--binary",
    "HEAD",
    "--",
    ".",
    `:(exclude)${generatedReleasePath}`,
    ...RELEASE_FINGERPRINT_EXCLUDED_PATHS.map((file) => `:(exclude)${file}`),
  ], "");
  const untracked = git(["ls-files", "--others", "--exclude-standard", "-z"], "")
    .split("\0")
    .filter((file) => file && !isReleaseFingerprintExcluded(file, generatedReleasePath))
    .sort();
  hash.update(trackedDiff);
  for (const file of untracked) {
    hash.update(`\0${file}\0`);
    try {
      hash.update(readFileSync(path.join(root, file)));
    } catch {
      hash.update("unreadable");
    }
  }
  return trackedDiff || untracked.length ? hash.digest("hex").slice(0, 12) : "";
}

const commitSha = releaseValue(process.env.REHABMIND_COMMIT_SHA, git(["rev-parse", "HEAD"], "workspace"));
const dirtyFingerprint = worktreeFingerprint();
const buildId = releaseValue(
  process.env.REHABMIND_BUILD_ID,
  `local-${commitSha.slice(0, 12)}${dirtyFingerprint ? `-dirty-${dirtyFingerprint}` : ""}`,
);
const packageVersion = releaseValue(packageMetadata.version, "0.0.0");
const knowledgeVersion = releaseValue(process.env.REHABMIND_KNOWLEDGE_VERSION, `rehabmind-pilot-knowledge-${packageVersion}`);
const decisionVersion = releaseValue(process.env.REHABMIND_DECISION_VERSION, `rehabmind-pilot-decision-${packageVersion}`);
const appVersion = `rehabmind-pilot-app-${packageVersion}+${buildId}.${commitSha.slice(0, 12)}`;
const target = path.join(root, generatedReleasePath);
const output = `// Generated by scripts/deploy/generate-pilot-release.mjs. Do not edit manually.\nexport const GENERATED_PILOT_RELEASE = Object.freeze(${JSON.stringify({
  packageVersion,
  appVersion,
  knowledgeVersion,
  decisionVersion,
  ruleVersion: decisionVersion,
  buildId,
  commitSha,
}, null, 2)} as const);\n`;
if (readFileSync(target, { encoding: "utf8", flag: "a+" }) !== output) writeFileSync(target, output, "utf8");
console.log(`pilot release: ${appVersion}`);
